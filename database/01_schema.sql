/* ===========================================================================
   SECTION 3 -- PEOPLE
   Role (parent)  ->  User (child)  ->  Employee / Party (subtypes)
   Exactly the shape asked for: role(roleid) then user(userid, roleid, ...).
   Staff, customers and suppliers are all users; what differs is the role and
   which subtype row hangs off the user.
   =========================================================================== */

CREATE TABLE "User" (
    user_id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id             INT          NOT NULL,
    /* Copied from "Role" only so the CHECK below can see it. The composite FK
       to "Role" (role_id, requires_email) with ON UPDATE CASCADE means it can
       never drift from the parent -- change the role's rule and every user
       row follows automatically. This is the trigger-free way to say
       "staff must have an e-mail, customers and suppliers need not". */
    requires_email      BOOLEAN      NOT NULL,
    full_name           VARCHAR(120) NOT NULL,
    email               VARCHAR(120) NULL UNIQUE,
    phone               VARCHAR(30)  NULL,
    password_hash       VARCHAR(200) NULL,
    primary_location_id INT          NULL,
    is_active           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at          DATE         NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT fk_user_role FOREIGN KEY (role_id)
        REFERENCES "Role" (role_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_user_email_rule FOREIGN KEY (role_id, requires_email)
        REFERENCES "Role" (role_id, requires_email)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_user_location FOREIGN KEY (primary_location_id)
        REFERENCES "Location" (location_id) ON UPDATE CASCADE ON DELETE SET NULL,

    /* THE RULE. Super Admin / Accountant / Order Dept / Sales cannot be saved
       without an e-mail; Customer / Supplier / Customer & Supplier can. The
       column UNIQUE above still stops two people sharing one address, and
       PostgreSQL allows any number of NULLs in a UNIQUE column, so every
       party may be left blank. */
    CONSTRAINT ck_user_email_required CHECK (
        requires_email = FALSE OR email IS NOT NULL
    ),
    CONSTRAINT ck_user_email_shape CHECK (
        email IS NULL OR email LIKE '%_@_%.__%'
    ),
    /* Anyone who signs in needs a password; parties never sign in. */
    CONSTRAINT ck_user_password CHECK (
        requires_email = FALSE OR password_hash IS NOT NULL
    )
);

ALTER TABLE "Location"
    ADD CONSTRAINT fk_location_incharge FOREIGN KEY (in_charge_user_id)
        REFERENCES "User" (user_id) ON UPDATE CASCADE ON DELETE SET NULL;

ALTER TABLE "FiscalPeriod"
    ADD CONSTRAINT fk_period_closed_by FOREIGN KEY (closed_by_user_id)
        REFERENCES "User" (user_id) ON UPDATE CASCADE ON DELETE SET NULL;

