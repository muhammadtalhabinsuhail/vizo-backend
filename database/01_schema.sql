       is one WHERE clause away. NULL on every other line. */
    party_user_id    INT          NULL,
    description      VARCHAR(300) NULL,
    debit_amount     DECIMAL(14,2) NOT NULL DEFAULT 0 CHECK (debit_amount >= 0),
    credit_amount    DECIMAL(14,2) NOT NULL DEFAULT 0 CHECK (credit_amount >= 0),
