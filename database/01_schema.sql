/* ===========================================================================
   SECTION 4 -- COURIERS AND DELIVERY CHANNELS
   =========================================================================== */

/* Every carrier the goods can leave on: courier companies, cargo companies,
   freight operators and the in-house rider. */
CREATE TABLE "Courier" (
    courier_id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    courier_name           VARCHAR(80)  NOT NULL UNIQUE,
    short_name             VARCHAR(30)  NOT NULL,
    contact_person         VARCHAR(80)  NULL,
    phone                  VARCHAR(30)  NULL,
    /* Days the courier holds cash-on-delivery money before settling. */
    cod_settlement_days    SMALLINT     NOT NULL DEFAULT 0 CHECK (cod_settlement_days >= 0),
    booking_charge         DECIMAL(14,2) NOT NULL DEFAULT 0 CHECK (booking_charge >= 0),
    cod_fee_percent        DECIMAL(5,2)  NOT NULL DEFAULT 0
        CHECK (cod_fee_percent BETWEEN 0 AND 100),
    tracking_url_template  VARCHAR(200) NULL,
    is_active              BOOLEAN      NOT NULL DEFAULT TRUE
);

/* How goods leave: own team, online courier, local cargo, heavy freight.
   Each route has a different person who can say "it arrived", which is the
   whole problem this system was built to solve. */
CREATE TABLE "DeliveryChannel" (
    channel_id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_key            VARCHAR(20)  NOT NULL UNIQUE,
    channel_name           VARCHAR(60)  NOT NULL,
    description            VARCHAR(200) NOT NULL,
    /* Which role is chased for the confirmation. */
    confirmed_by_role_id   INT          NOT NULL,
    remind_after_days      SMALLINT     NOT NULL DEFAULT 0 CHECK (remind_after_days >= 0),
    remind_every_hours     SMALLINT     NOT NULL DEFAULT 24 CHECK (remind_every_hours > 0),
    auto_confirm           BOOLEAN      NOT NULL DEFAULT FALSE,
    /* Freight and cargo have no tracking feed -- the bilty receipt is the
       only proof, so its number is mandatory on those channels. */
    requires_bilty         BOOLEAN      NOT NULL DEFAULT FALSE,
    is_active              BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_channel_role FOREIGN KEY (confirmed_by_role_id)
        REFERENCES "Role" (role_id) ON UPDATE CASCADE ON DELETE CASCADE
);

/* The frontend keeps a carriers[] array on each channel. An array is not
   1NF, so it becomes this junction. */
CREATE TABLE "ChannelCarrier" (
    channel_id       INT NOT NULL,
    courier_id       INT NOT NULL,
    PRIMARY KEY (channel_id, courier_id),
    CONSTRAINT fk_cc_channel FOREIGN KEY (channel_id)
        REFERENCES "DeliveryChannel" (channel_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_cc_courier FOREIGN KEY (courier_id)
        REFERENCES "Courier" (courier_id) ON UPDATE CASCADE ON DELETE CASCADE
);


