/* ===========================================================================
   ADVANCE POS SYSTEM (AdvPOS) -- PostgreSQL schema
   Tenant modelled: VIZO Pakistan -- mobile-accessories distribution.
   Derived from the frontend at github.com/AmmarKamran2005/advpos-frontend
   ---------------------------------------------------------------------------
   RULES HONOURED

     * PostgreSQL only.
     * 1NF / 2NF / 3NF. Repeating groups (barcodes, carriers, permissions,
       collection allocations) are broken out into child tables. Transitive
       dependencies (city -> province, account -> type -> group) are removed.
     * No CREATE TYPE ... AS ENUM anywhere. Every closed value set is a
       lookup table joined by a parent -> child foreign key.
     * Table names in PascalCase, therefore double-quoted. Column names are
       lower snake_case so everyday SQL stays unquoted and readable.
     * No stored procedures, no triggers, no functions.
     * Primary and foreign keys only. No CREATE INDEX. UNIQUE appears only
       where a duplicate would be a real bug: e-mail, party code, SKU,
       document numbers.
     * Money is DECIMAL(14,2), percentages DECIMAL(5,2). No FLOAT anywhere.
     * ON UPDATE CASCADE on every foreign key. ON DELETE CASCADE where the
       child is owned by the parent, ON DELETE SET NULL where the reference
       is optional. No foreign key ever blocks a delete.
     * Document status is a lookup table plus a current-status FK on the
       document. Status HISTORY is deliberately not here -- it is delivered
       separately in 04_status_history.sql.

   FILE ORDER:  01_schema.sql  ->  02_seed.sql  ->  03_sequence_reset.sql
   =========================================================================== */


