    CONSTRAINT fk_visit_rep FOREIGN KEY (sales_person_user_id)
        REFERENCES "Employee" (user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_visit_outcome FOREIGN KEY (outcome_id)
        REFERENCES "VisitOutcome" (outcome_id) ON UPDATE CASCADE ON DELETE CASCADE
);


/* ===========================================================================
   SECTION 11 -- NOTIFICATIONS AND HISTORY
   Reminders are NOT stored. A claim that has sat too long produces a reminder
   because of its dates; settle it and the reminder disappears on its own.
   Storing them would mean rows to tick off and rows going stale.
   =========================================================================== */

CREATE TABLE "Notification" (
    notification_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          INT          NOT NULL,
    severity_id      INT          NOT NULL,
    icon             VARCHAR(40)  NOT NULL,
    title            VARCHAR(120) NOT NULL,
    body             VARCHAR(300) NOT NULL,
    created_at       TIMESTAMP    NOT NULL,
    is_read          BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_notif_user FOREIGN KEY (user_id)
        REFERENCES "User" (user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_notif_severity FOREIGN KEY (severity_id)
        REFERENCES "SeverityLevel" (severity_id) ON UPDATE CASCADE ON DELETE CASCADE
);

/* HISTORY ENTITY -- Activity History / audit trail. Who did what, to which
   record, from which machine. user_id is nullable because the system itself
   posts entries, and a failed login has no authenticated user. */
CREATE TABLE "ActivityLog" (
    log_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INT          NULL,
    action_name       VARCHAR(30)  NOT NULL,
    entity_type       VARCHAR(40)  NOT NULL,
    entity_reference  VARCHAR(60)  NOT NULL,
    detail            VARCHAR(300) NULL,
    ip_address        VARCHAR(45)  NULL,
    location_id       INT          NULL,
    severity_id       INT          NOT NULL,
    logged_at         TIMESTAMP    NOT NULL,
    CONSTRAINT fk_log_user FOREIGN KEY (user_id)
        REFERENCES "User" (user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_log_location FOREIGN KEY (location_id)
        REFERENCES "Location" (location_id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_log_severity FOREIGN KEY (severity_id)
        REFERENCES "SeverityLevel" (severity_id) ON UPDATE CASCADE ON DELETE CASCADE
);

/* HISTORY ENTITY -- Backup & Restore. */
CREATE TABLE "BackupHistory" (
    backup_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at        TIMESTAMP    NOT NULL,
    backup_type_id    INT          NOT NULL,
    status_id         INT          NOT NULL,
    size_mb           DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (size_mb >= 0),
    destination       VARCHAR(80)  NOT NULL,
    duration_seconds  INT          NOT NULL DEFAULT 0 CHECK (duration_seconds >= 0),
    checksum_hash     VARCHAR(80)  NULL,
    triggered_by_user_id INT       NULL,
    CONSTRAINT fk_backup_type FOREIGN KEY (backup_type_id)
        REFERENCES "BackupType" (backup_type_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_backup_status FOREIGN KEY (status_id)
        REFERENCES "BackupStatus" (status_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_backup_user FOREIGN KEY (triggered_by_user_id)
        REFERENCES "User" (user_id) ON UPDATE CASCADE ON DELETE SET NULL
);

