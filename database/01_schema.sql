/* ===========================================================================
   SECTION 6 -- ACCOUNTING CORE
   ---------------------------------------------------------------------------
   ONE SOURCE OF TRUTH. Every rupee that ever moves lands in exactly one
   place: "JournalEntryLine". Nothing else stores a balance.

       Ledger        = the lines of one account, ordered by date
       Trial balance = SUM(debit), SUM(credit) grouped by account
       Manual entry  = a "JournalEntry" whose type is JOURNAL, keyed by hand
       P&L / Balance sheet = the same sums rolled up by account type -> group

   "Account" therefore carries an opening_balance and nothing else. A stored
   running balance would be a second truth that drifts the first time
   somebody edits an entry.
   =========================================================================== */

CREATE TABLE "AccountGroup" (
    group_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name        VARCHAR(40)  NOT NULL UNIQUE,
