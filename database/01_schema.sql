/* Customer / supplier subtype. Whether a party buys, supplies or both is
   already carried by its role, so it is not repeated here. */
CREATE TABLE "Party" (
    user_id                INT          PRIMARY KEY,
    party_code             VARCHAR(15)  NOT NULL UNIQUE,
    legal_name             VARCHAR(200) NOT NULL,
    display_name           VARCHAR(150) NULL,
    category_id            INT          NOT NULL,
    city_id                INT          NOT NULL,
    address_line           VARCHAR(200) NULL,
    alt_phone              VARCHAR(30)  NULL,
    industry               VARCHAR(100) NULL,
    /* One tax registration cannot belong to two businesses. Nullable: most
       small shops are not registered at all. */
    ntn                    VARCHAR(20)  NULL UNIQUE,
    strn                   VARCHAR(30)  NULL UNIQUE,
    cnic                   VARCHAR(20)  NULL UNIQUE,
    credit_limit           DECIMAL(14,2) NOT NULL DEFAULT 0 CHECK (credit_limit >= 0),
    credit_days            INT          NOT NULL DEFAULT 0 CHECK (credit_days >= 0),
    hold_policy_id         INT          NOT NULL,
    opening_balance        DECIMAL(14,2) NOT NULL DEFAULT 0,
    /* The rep who owns the relationship. Must be a member of staff. */
    sales_person_user_id   INT          NULL,
    default_location_id    INT          NULL,
    rating                 CHAR(1)      NOT NULL DEFAULT 'B'
        CHECK (rating IN ('A','B','C','D')),
    notes                  VARCHAR(500) NULL,

    CONSTRAINT fk_party_user FOREIGN KEY (user_id)
        REFERENCES "User" (user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_party_category FOREIGN KEY (category_id)
        REFERENCES "PartyCategory" (category_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_party_city FOREIGN KEY (city_id)
        REFERENCES "City" (city_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_party_hold_policy FOREIGN KEY (hold_policy_id)
        REFERENCES "CreditHoldPolicy" (policy_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_party_salesperson FOREIGN KEY (sales_person_user_id)
        REFERENCES "Employee" (user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_party_location FOREIGN KEY (default_location_id)
        REFERENCES "Location" (location_id) ON UPDATE CASCADE ON DELETE SET NULL
);

