    CONSTRAINT uq_dsh_event UNIQUE (delivery_id, status_id, changed_at),
    CONSTRAINT fk_dsh_delivery FOREIGN KEY (delivery_id)
        REFERENCES "Delivery" (delivery_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_dsh_status FOREIGN KEY (status_id)
        REFERENCES "DeliveryStatus" (status_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_dsh_user FOREIGN KEY (changed_by_user_id)
        REFERENCES "User" (user_id) ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE TABLE "InvoiceStatusHistory" (
    history_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id          INT          NOT NULL,
    status_id           INT          NOT NULL,
    changed_by_user_id  INT          NULL,
    changed_at          TIMESTAMP    NOT NULL,
    note                VARCHAR(300) NULL,
    CONSTRAINT uq_ish_event UNIQUE (invoice_id, status_id, changed_at),
    CONSTRAINT fk_ish_invoice FOREIGN KEY (invoice_id)
        REFERENCES "SalesInvoice" (invoice_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_ish_status FOREIGN KEY (status_id)
        REFERENCES "InvoiceStatus" (status_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_ish_user FOREIGN KEY (changed_by_user_id)
        REFERENCES "User" (user_id) ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE TABLE "CollectionStatusHistory" (
    history_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id       INT          NOT NULL,
    status_id           INT          NOT NULL,
    changed_by_user_id  INT          NULL,
    changed_at          TIMESTAMP    NOT NULL,
    note                VARCHAR(300) NULL,
    CONSTRAINT uq_clsh_event UNIQUE (collection_id, status_id, changed_at),
    CONSTRAINT fk_clsh_collection FOREIGN KEY (collection_id)
        REFERENCES "Collection" (collection_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_clsh_status FOREIGN KEY (status_id)
        REFERENCES "CollectionStatus" (status_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_clsh_user FOREIGN KEY (changed_by_user_id)
        REFERENCES "User" (user_id) ON UPDATE CASCADE ON DELETE SET NULL
);

