/* ===========================================================================
   ADVANCE POS SYSTEM (AdvPOS) -- STATUS HISTORY
   ---------------------------------------------------------------------------
   THIS FILE IS NOT PART OF THE DATABASE.

   01_schema.sql gives every document its CURRENT status and stops there:
   SalesOrder.status_id, Claim.stage_id, Delivery.status_id, and so on. That
   answers "where is this order now?" and nothing else.

   You asked how to also answer "who marked ORD-26-0142 dispatched, and when?"
   -- and asked for it kept separate. Here it is. Load it only if you want the
   trail. Everything else keeps working whether you load it or not.
   ===========================================================================

   THE IDEA
   ---------------------------------------------------------------------------
   A status history table is a plain child of the document. One row per change,
   never updated, never deleted:

       (which document, which status, who did it, when, and why)

   It reuses the SAME status lookup the document already points at, so
   OrderStatusHistory.status_id and SalesOrder.status_id speak one vocabulary.
   No new enums, no triggers -- the backend writes the document and its history
   row inside one transaction, which is two INSERT/UPDATE statements it is
   already issuing anyway.

   WHY KEEP status_id ON THE DOCUMENT AS WELL
   ---------------------------------------------------------------------------
   You could drop SalesOrder.status_id and read the newest history row instead.
   Do not. Every order list, every dashboard count and every reminder filters
   on the current status, and each of those would turn into a "latest row per
   order" subquery. Keeping the column costs one extra write and saves that
   query everywhere.

   So: the column is the current state, the history table is the trail. The
   backend keeps them in step in one transaction:

       BEGIN;
         UPDATE "SalesOrder" SET status_id = 7 WHERE order_id = 1;
         INSERT INTO "OrderStatusHistory"
                (order_id, status_id, changed_by_user_id, changed_at, note)
         VALUES (1, 7, 4, NOW(), 'Handed to the rep on the evening round');
       COMMIT;

   A trigger would do this for you, and would also hide it, break bulk loads,
   and make the seed above impossible to reason about. Two lines in one
   transaction is the simpler answer.
   =========================================================================== */


/* ---------------------------------------------------------------------------
   PATTERN A -- one history table per document  (RECOMMENDED)

   More tables, but every foreign key stays real: an order's history cannot
   accidentally point at an invoice status, and deleting the order takes its
   trail with it.
   --------------------------------------------------------------------------- */

CREATE TABLE "OrderStatusHistory" (
    history_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            INT          NOT NULL,
    status_id           INT          NOT NULL,
    changed_by_user_id  INT          NULL,
    changed_at          TIMESTAMP    NOT NULL,
    note                VARCHAR(300) NULL,
    /* The same order cannot be marked the same status twice at the same
       instant -- that is a double-submit, not two events. */
    CONSTRAINT uq_osh_event UNIQUE (order_id, status_id, changed_at),
    CONSTRAINT fk_osh_order FOREIGN KEY (order_id)
        REFERENCES "SalesOrder" (order_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_osh_status FOREIGN KEY (status_id)
        REFERENCES "OrderStatus" (status_id) ON UPDATE CASCADE ON DELETE CASCADE,
    /* SET NULL, not CASCADE: sacking a member of staff must not erase the
       fact that the order was dispatched. */
    CONSTRAINT fk_osh_user FOREIGN KEY (changed_by_user_id)
        REFERENCES "User" (user_id) ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE TABLE "ClaimStageHistory" (
    history_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id            INT          NOT NULL,
    stage_id            INT          NOT NULL,
    changed_by_user_id  INT          NULL,
    changed_at          TIMESTAMP    NOT NULL,
    note                VARCHAR(300) NULL,
    CONSTRAINT uq_csh_event UNIQUE (claim_id, stage_id, changed_at),
    CONSTRAINT fk_csh_claim FOREIGN KEY (claim_id)
        REFERENCES "Claim" (claim_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_csh_stage FOREIGN KEY (stage_id)
        REFERENCES "ClaimStage" (stage_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_csh_user FOREIGN KEY (changed_by_user_id)
        REFERENCES "User" (user_id) ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE TABLE "DeliveryStatusHistory" (
    history_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id         INT          NOT NULL,
    status_id           INT          NOT NULL,
